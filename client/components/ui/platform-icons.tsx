export function PlatformBadge({ platform, size = 'sm' }: { platform: string; size?: 'sm' | 'md' }) {
  const p = platform.toLowerCase();
  const iconSize = size === 'sm' ? 'w-3 h-3' : 'w-3.5 h-3.5';
  
  if (p === 'instagram' || p === 'ig') {
    return (
      <div className="flex items-center justify-center w-5 h-5 rounded-full bg-gradient-to-tr from-amber-500 via-rose-500 to-purple-600 text-white shadow-2xs">
        <InstagramIcon className={iconSize} />
      </div>
    );
  }
  if (p === 'linkedin' || p === 'li') {
    return (
      <div className="flex items-center justify-center w-5 h-5 rounded-full bg-[#0A66C2] text-white shadow-2xs">
        <LinkedInIcon className={iconSize} />
      </div>
    );
  }
  if (p === 'x' || p === 'twitter') {
    return (
      <div className="flex items-center justify-center w-5 h-5 rounded-full bg-gray-900 text-white shadow-2xs">
        <XIcon className={iconSize} />
      </div>
    );
  }
  if (p === 'facebook' || p === 'fb') {
    return (
      <div className="flex items-center justify-center w-5 h-5 rounded-full bg-[#1877F2] text-white shadow-2xs">
        <FacebookIcon className={iconSize} />
      </div>
    );
  }
  if (p === 'tiktok' || p === 'tt') {
    return (
      <div className="flex items-center justify-center w-5 h-5 rounded-full bg-black text-white shadow-2xs">
        <TikTokIcon className={iconSize} />
      </div>
    );
  }
  return null;
}
